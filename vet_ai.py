def ask_vet_ai(question: str) -> dict:
    """
    Анализирует вопрос пользователя и выдает экспертный персонализированный ответ
    с учетом веса Тучи и Грунтика.
    """
    q = (question or "").strip().lower()
    if not q:
        return {
            "answer": "Пожалуйста, задайте вопрос о здоровье, поведении или питании котиков (например: «можно ли коту сыр?», «сколько воды должен пить?», «чихает»)",
            "urgency": "normal",
            "tips": ["Питание", "Токсичные продукты", "Норма воды", "Обработка от паразитов"]
        }

    # Получаем профили Тучи и Грунтика для персонализации
    cats = database.get_cats()
    cat_info_str = ""
    avg_weight = 4.0
    weights = []
    for c in cats:
        w = c.get("weight")
        if w:
            weights.append(float(w))
    if weights:
        avg_weight = sum(weights) / len(weights)
        cat_info_str = f" (вес Тучи/Грунтика в базе: {', '.join([f'{c['name']}: {c.get('weight') or 4.0} кг' for c in cats])})"

    # 1. Проверка на токсичные продукты
    for toxic_kw, response_text in TOXIC_ITEMS.items():
        if re.search(r'\b' + re.escape(toxic_kw) + r'\w*', q):
            return {
                "answer": response_text,
                "urgency": "warning",
                "tips": ["Никогда не давать со стола", "Держать в закрытых шкафах"],
                "cat_specific": f"Берегите Тучу и Грунтика{cat_info_str}!"
            }

    # 2. Проверка на популярные темы
    if any(k in q for k in ["вод", "пить", "жажд", "обезвож"]):
        daily_ml = int(avg_weight * 45)
        ans = POPULAR_TOPICS["норма воды"] + f"\n\n🐾 <b>Для Тучи и Грунтика{cat_info_str}:</b> норма составляет примерно <b>{daily_ml} мл</b> на котика в день."
        return {
            "answer": ans,
            "urgency": "normal",
            "tips": ["Менять воду ежедневно", "Широкая керамическая миска"]
        }

    if any(k in q for k in ["чих", "сопл", "глаз", "слез", "нос"]):
        return {
            "answer": POPULAR_TOPICS["чихает"],
            "urgency": "normal" if "кров" not in q else "warning",
            "tips": ["Проверить наполнитель", "Осмотреть глаза на выделения"]
        }

    if any(k in q for k in ["рвот", "тошн", "блев", "срыг"]):
        return {
            "answer": POPULAR_TOPICS["рвота"],
            "urgency": "warning",
            "tips": ["Мальт-паста от шерсти", "Следить за аппетитом и активностью"]
        }

    if any(k in q for k in ["глист", "блох", "клещ", "паразит", "капл", "мильбемакс", "стронгхолд", "селафорт"]):
        ans = POPULAR_TOPICS["обработка от блох и глистов"]
        if weights:
            ans += f"\n\n⚖️ <b>Расчет по текущему весу котиков{cat_info_str}:</b>\n"
            for c in cats:
                cw = c.get("weight") or 4.0
                ans += f"• <b>{c['name']}</b> ({cw} кг) ➔ категория препаратов «для кошек 2–4 кг» или «для кошек 4–8 кг» в зависимости от точной шкалы производителя.\n"
        return {
            "answer": ans,
            "urgency": "normal",
            "tips": ["Взвесить перед покупкой", "Не использовать собачьи препараты"]
        }

    if any(k in q for k in ["лоток", "моч", "писа", "туалет", "мкб", "цистит"]):
        return {
            "answer": POPULAR_TOPICS["лоток"],
            "urgency": "warning",
            "tips": ["Чистить лоток 1-2 раза в день", "Контролировать объем мочи"]
        }

    if any(k in q for k in ["корм", "ед", "питан", "чем кормить", "лакомств", "паучи"]):
        return {
            "answer": POPULAR_TOPICS["чем кормить"],
            "urgency": "normal",
            "tips": ["Премиум/супер-премиум корм", "Свежая вода рядом"]
        }

    if any(k in q for k in ["вес", "толст", "похуд", "взвешиван"]):
        ans = (
            f"⚖️ <b>Контроль веса Тучи и Грунтика:</b>\n\n"
            f"• Норма веса взрослой беспородной кошки среднего размера: <b>3.5 – 5.0 кг</b>.\n"
            f"• В базе записано{cat_info_str}.\n"
            f"• <b>Как проверить кондицию</b>: ребра котика должны легко прощупываться под легким слоем жирка, "
            f"а при взгляде сверху должна быть заметна талия. Если котик весит больше 5.5–6 кг, стоит проконсультироваться "
            f"с ветеринаром по снижению калорийности порций."
        )
        return {
            "answer": ans,
            "urgency": "normal",
            "tips": ["Взвешивать раз в месяц", "Соблюдать граммовку на пачке корма"]
        }

    if any(k in q for k in ["растен", "цвет", "цветы", "трава", "папоротник"]):
        ans = (
            "🌿 <b>Растения и котики:</b>\n\n"
            "• <b>Смертельно опасны</b>: Лилии (все виды), Диффенбахия, Монстера, Азалия, Фикусы, Олеандр.\n"
            "• <b>Безопасны для кошек</b>: Хлорофитум, Калатея, Папоротник Бостонский, Бамбуковая пальма.\n"
            "• <b>Рекомендуется</b>: купите или посадите специальную кошачью травку (пророщенный овес или пшеницу). "
            "Котики обожают её жевать для очищения желудка от шерсти!"
        )
        return {
            "answer": ans,
            "urgency": "normal",
            "tips": ["Убрать опасные цветы на высоту", "Купить кошачью траву"]
        }

    # 3. Общий ответ с полезными ориентирами
    ans = (
        f"🐾 <b>Совет вет-консультанта:</b>\n\n"
        f"По вашему вопросу (<i>«{question}»</i>): домашние черные котики Туча и Грунтик{cat_info_str} "
        f"нуждаются в сбалансированном рационе, регулярных профилактических обработках и достаточном питьевом режиме.\n\n"
        f"📌 <b>Главные ориентиры здоровья:</b>\n"
        f"1. Хороший аппетит и регулярное питье воды (не менее 150 мл/сутки).\n"
        f"2. Активность и готовность побегать за дразнилкой.\n"
        f"3. Блестящая чистая шерстка и чистые глазки/ушки.\n"
        f"4. Регулярный туалет (1-2 раза в сутки по-большому, 2-4 раза по-маленькому).\n\n"
        f"Если вы заметили вялость, отказ от еды или необычное поведение — обязательно покажите котиков ветеринару."
    )
    return {
        "answer": ans,
        "urgency": "normal",
        "tips": ["Питание", "Вода", "Лоток", "Обработка от паразитов"]
    }
